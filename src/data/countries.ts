export const COUNTRIES: Country[] = ROWS.map(([code, en, fr]) => ({ code, en, fr }));

/** The flag of a country code (regional indicator symbols). */
export const flagOf = (code: string) => String.fromCodePoint(...[...code.toUpperCase()].map((ch) => 0x1f1e6 + ch.charCodeAt(0) - 65));

const plain = (s: string) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().trim();

/** The country a stored value names (its English or French name, or its code), if any. */
export function findCountry(value: string | null | undefined): Country | undefined {
  const v = plain(value ?? "");
  if (!v) return undefined;
  return COUNTRIES.find((c) => plain(c.en) === v || plain(c.fr) === v || c.code.toLowerCase() === v);
}

/** Countries matching a search, in either language; names that start with it come first. */
export function searchCountries(q: string): Country[] {
  const v = plain(q);
  if (!v) return COUNTRIES;
  const hit = COUNTRIES.filter((c) => plain(c.en).includes(v) || plain(c.fr).includes(v) || c.code.toLowerCase() === v);
  const starts = (c: Country) => plain(c.en).startsWith(v) || plain(c.fr).startsWith(v);
  return [...hit.filter(starts), ...hit.filter((c) => !starts(c))];
}
