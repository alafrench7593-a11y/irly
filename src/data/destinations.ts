export function getDestination(id: DestinationId): Destination {
  return DESTINATIONS[id];
}

export function getCity(id: CityId): City {
  return CITIES[id];
}

export function citiesOf(destinationId: DestinationId): City[] {
  return DESTINATIONS[destinationId].cities.map((id) => CITIES[id]);
}

export function areaName(city: City, areaId: string): string {
  return city.areas.find((a) => a.id === areaId)?.name ?? city.name;
}
