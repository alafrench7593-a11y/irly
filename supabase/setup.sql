-- IRLY database setup: this file is intentionally empty of schema.
--
-- The database is built by applying every file of supabase/migrations, in
-- file-name order, each in its own transaction, recorded in
-- private.irly_migrations:
--
--   SUPABASE_ACCESS_TOKEN=sbp_... node scripts/deploy-db.mjs
--
-- (run by .github/workflows/supabase.yml on every push). Locally, the same
-- migrations are applied to a throwaway PostgreSQL database by
-- scripts/test-db.sh, which also runs supabase/tests.
--
-- This file used to hold a copy of the first six migrations only (of more
-- than a hundred) while presenting itself as a full setup: pasting it into
-- the SQL editor produced an incomplete and insecure schema. Do not paste
-- SQL by hand; run scripts/deploy-db.mjs instead. A project that was set up
-- with that old copy is detected by deploy-db.mjs (it records the first
-- migrations as applied and applies the rest).
select 'IRLY: apply supabase/migrations with scripts/deploy-db.mjs; this file installs nothing' as notice;
